export const DICTS: Record<Lang, typeof de> = { de, en, ru };

export type TKey = keyof typeof de;

interface I18n {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: TKey, params?: Record<string, string | number>) => string;
}

export const LangContext = createContext<I18n>({
  lang: "de",
  setLang: () => undefined,
  t: (key) => DICTS.de[key] ?? key,
});

export function useI18n(): I18n {
  return useContext(LangContext);
}

/** Initial language: saved choice → browser locale → German. */
export function detectLang(): Lang {
  const saved = localStorage.getItem("dokumente.lang");
  if (saved === "de" || saved === "en" || saved === "ru") return saved;
  const nav = navigator.language.slice(0, 2).toLowerCase();
  if (nav === "ru") return "ru";
  if (nav === "en") return "en";
  return "de";
}

/**
 * Renders a day count as text, in one place. German and English have no
 * plural-safe abbreviation the way Russian's "дн." does, so "in 1 Tagen" and
 * "1 days overdue" were showing on the app's most prominent screen — the
 * Telegram side has had `pluralDaysSt` for exactly this since day one.
 *
 * NaN (an unparseable server date) renders as an em dash, never as a bogus
 * day count.
 */
export function formatDaysLeft(t: I18n["t"], days: number): string {
  if (Number.isNaN(days)) return "—";
  if (days === 0) return t("dash.today");
  if (days === 1) return t("dash.inOneDay");
  if (days === -1) return t("dash.overdueOne");
  return days < 0
    ? t("dash.overdue", { n: -days })
    : t("dash.inDays", { n: days });
}
